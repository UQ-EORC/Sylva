#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uniform_is_numpys() {
        // np.random.default_rng(5).uniform(-0.3, 0.3, 3)
        let mut g = Generator::new(5);
        assert_eq!(g.uniform_n(-0.3, 0.3, 3), vec![0.1830017542472281, 0.18476447384189626, 0.009195336625285211]);
    }

    #[test]
    fn normal_is_numpys() {
        // np.random.default_rng(6).normal(0, 2.5, 3)
        let mut g = Generator::new(6);
        assert_eq!(g.normal_n(0.0, 2.5, 3), vec![2.6327893862168956, 4.441228259542482, -6.383229596142534]);
        // np.random.default_rng(0).standard_normal(304)[-1]: the first draw
        // from the tail beyond the base layer.
        let mut g = Generator::new(0);
        let z: Vec<f64> = (0..304).map(|_| g.standard_normal()).collect();
        assert_eq!(z[303], -3.772275156122734);
        assert!(z[..303].iter().all(|v| v.abs() < 3.66));
    }

    #[test]
    fn integers_are_numpys() {
        // np.random.default_rng(7).integers(-3, 9, 5), then .integers(0, 2**40)
        let mut g = Generator::new(7);
        let a: Vec<i64> = (0..5).map(|_| g.integers(-3, 9)).collect();
        assert_eq!(a, vec![8, 4, 5, 7, 3]);
        assert_eq!(g.integers(0, 1 << 40), 247617924053);
    }
}
