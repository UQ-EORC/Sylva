impl Generator {
    /// `Generator.standard_exponential()`: NumPy's exponential ziggurat (its
    /// default `zig` method), with the `log1p(-u)` tail NumPy uses.
    pub fn standard_exponential(&mut self) -> f64 {
        loop {
            let mut ri = self.next_u64();
            ri >>= 3;
            let idx = (ri & 0xff) as usize;
            ri >>= 8;
            let x = ri as f64 * WE[idx];
            if ri < KE[idx] {
                return x;
            }
            if idx == 0 {
                return ZIGGURAT_EXP_R - (-self.random()).ln_1p();
            } else if (FE[idx - 1] - FE[idx]) * self.random() + FE[idx] < (-x).exp() {
                return x;
            }
        }
    }

    /// `Generator.exponential(scale)`: `scale * standard_exponential()`.
    pub fn exponential(&mut self, scale: f64) -> f64 {
        scale * self.standard_exponential()
    }

    /// `n` draws of [`Generator::exponential`], as `exponential(scale, n)`.
    pub fn exponential_n(&mut self, scale: f64, n: usize) -> Vec<f64> {
        (0..n).map(|_| self.exponential(scale)).collect()
    }
}

