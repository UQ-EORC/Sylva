//! NumPy's `Generator` distributions on [`Generator`], reproduced to the bit.
//!
//! `uniform(low, high)` is `low + (high - low) * random()`; `integers` draws
//! by Lemire's method as `bounded` does; `standard_normal` is NumPy's
//! 256-layer ziggurat (Marsaglia and Tsang 2000, with the exponential tail
//! sampler and the `log1p(-u)` form NumPy uses), on NumPy's own tables, and
//! `standard_exponential` its 256-layer exponential ziggurat. A seeded
//! computation that moved from NumPy into the core therefore draws the same
//! numbers the NumPy code drew.

use crate::util::nprandom::Generator;

const ZIGGURAT_NOR_R: f64 = 3.654152885361009;
const ZIGGURAT_NOR_INV_R: f64 = 0.2736612373297583;
const ZIGGURAT_EXP_R: f64 = 7.6971174701310497140446280481;

impl Generator {
    /// `Generator.uniform(low, high)`: one draw from `[low, high)`.
    pub fn uniform(&mut self, low: f64, high: f64) -> f64 {
        let range = high - low;
        low + range * self.random()
    }

    /// `n` draws of [`Generator::uniform`], as `uniform(low, high, n)`.
    pub fn uniform_n(&mut self, low: f64, high: f64, n: usize) -> Vec<f64> {
        (0..n).map(|_| self.uniform(low, high)).collect()
    }

    /// `Generator.standard_normal()`: NumPy's ziggurat.
    pub fn standard_normal(&mut self) -> f64 {
        loop {
            let mut r = self.next_u64();
            let idx = (r & 0xff) as usize;
            r >>= 8;
            let sign = r & 0x1;
            let rabs = (r >> 1) & 0x000f_ffff_ffff_ffff;
            let mut x = rabs as f64 * WI[idx];
            if sign & 0x1 == 1 {
                x = -x;
            }
            if rabs < KI[idx] {
                return x;
            }
            if idx == 0 {
                loop {
                    let xx = -ZIGGURAT_NOR_INV_R * (-self.random()).ln_1p();
                    let yy = -(-self.random()).ln_1p();
                    if yy + yy > xx * xx {
                        return if (rabs >> 8) & 0x1 == 1 { -(ZIGGURAT_NOR_R + xx) } else { ZIGGURAT_NOR_R + xx };
                    }
                }
            } else if (FI[idx - 1] - FI[idx]) * self.random() + FI[idx] < (-0.5 * x * x).exp() {
                return x;
            }
        }
    }

    /// `Generator.normal(loc, scale)`: `loc + scale * standard_normal()`.
    pub fn normal(&mut self, loc: f64, scale: f64) -> f64 {
        loc + scale * self.standard_normal()
    }

    /// `n` draws of [`Generator::normal`], as `normal(loc, scale, n)`.
    pub fn normal_n(&mut self, loc: f64, scale: f64, n: usize) -> Vec<f64> {
        (0..n).map(|_| self.normal(loc, scale)).collect()
    }

    /// `Generator.integers(low, high)` (int64, `high` excluded). Panics if
    /// `high <= low`.
    pub fn integers(&mut self, low: i64, high: i64) -> i64 {
        assert!(high > low, "high <= low");
        let range = (high as u64).wrapping_sub(low as u64).wrapping_sub(1);
        (low as u64).wrapping_add(self.bounded(range)) as i64
    }
}

