"""Write THIRD_PARTY_LICENSES.md: the licence texts of the Rust crates that
are compiled into Sylva's binaries (the Python wheel and the `sylva` command).

Their licences (MIT, Apache-2.0, BSD, ISC, Zlib and similar) require the
copyright notice and the licence text to accompany a binary distribution.
The crates are taken from `cargo metadata` (normal and build dependencies of
the workspace crates, every platform; development dependencies are left
out), and the texts from the crates' own sources in the cargo registry, so
run `cargo fetch` first. Identical texts are printed once, with the crates
they cover. Run from the repository root after changing dependencies:

    python scripts/third_party_licenses.py
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE|PATENTS)", re.I)


def main() -> int:
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1"], cwd=ROOT, check=True,
                                     capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    seen, stack = set(), list(members)
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            # a dependency edge that is only a development dependency is not linked into a release
            if all(k["kind"] == "dev" for k in dep["dep_kinds"]):
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    crates = sorted((packages[i] for i in seen - members), key=lambda p: (p["name"].lower(), p["version"]))
    texts: dict[str, tuple[str, list[str]]] = {}
    missing = []
    for p in crates:
        src = Path(p["manifest_path"]).parent
        files = sorted(f for f in src.iterdir() if f.is_file() and NAMES.match(f.name))
        if not files:
            missing.append(f"{p['name']} {p['version']} ({p.get('license')})")
        for f in files:
            body = f.read_text(errors="replace").replace("\r\n", "\n").strip()
            key = hashlib.sha256(re.sub(r"\s+", " ", body).encode()).hexdigest()
            texts.setdefault(key, (body, []))[1].append(f"{p['name']} {p['version']} ({f.name})")
    out = ["# Licences of the Rust crates compiled into Sylva", "",
           "Sylva's binaries (the Python wheel's extension module and the `sylva` command)",
           "are built from the Rust crates listed here, whose licences ask that their",
           "copyright notices and licence texts accompany a binary distribution. Sylva",
           "itself is under the GNU General Public License v3.0 or later (`LICENSE`); code",
           "adapted from other projects is listed in `THIRD_PARTY_NOTICES.md`.", "",
           "Generated by `scripts/third_party_licenses.py`; do not edit by hand.", "",
           "## Crates", "", "| Crate | Version | Licence | Source |", "|---|---|---|---|"]
    for p in crates:
        out.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see its licence file'} | {p.get('repository') or ''} |")
    if missing:
        out += ["", "No licence file is included in the published source of: " + "; ".join(missing) + ".",
                "Their licences are the ones named in the table; the standard texts appear below under other crates."]
    out += ["", "## Licence texts", ""]
    for body, users in sorted(texts.values(), key=lambda t: (-len(t[1]), t[1][0].lower())):
        out += ["### " + ", ".join(users), "", "```text", body.replace("```", "'''"), "```", ""]
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(out).rstrip() + "\n")
    print(f"{len(crates)} crates, {len(texts)} distinct licence texts, {len(missing)} without a licence file")
    for m in missing:
        print("  no licence file:", m)
    return 0


if __name__ == "__main__":
    sys.exit(main())
