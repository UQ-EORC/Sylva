"""Write ``python/sylva/_core.pyi``, the type stub of the compiled core.

The core is a pyo3 extension: every function carries the signature pyo3 writes
from its ``#[pyo3(signature = ...)]``, which is what editors and type checkers
read from the stub. Argument and return types are not known to pyo3, so they
are ``Any``; the Python wrappers in ``sylva.*`` carry the documented types.

Run after ``maturin develop``; ``tests/test_stub.py`` checks the stub is current.
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

HEADER = '''"""Type stub of ``sylva._core``, generated by ``scripts/gen_core_stub.py``.

Signatures come from the pyo3 bindings; types are not tracked across the
boundary, so arguments and returns are ``Any``. The documented API is the
Python layer, ``sylva.*``.
"""

from typing import Any

__version__: str
'''


def _signature(obj) -> str:
    text = obj.__text_signature__ or "(*args, **kwargs)"
    text = text.replace("($self, ", "(self, ").replace("($self)", "(self)")
    text = text.replace("($cls, ", "(cls, ").replace("($cls)", "(cls)")
    text = text.replace("($module, ", "(").replace("($module)", "()")
    return text


def render(core) -> str:
    out = [HEADER]
    names = sorted(n for n in dir(core) if not n.startswith("_"))
    for name in names:
        obj = getattr(core, name)
        if inspect.isclass(obj):
            continue
        if not callable(obj):
            out.append(f"{name}: {type(obj).__name__}")
    out.append("")
    for name in names:
        obj = getattr(core, name)
        if inspect.isclass(obj):
            out.append(f"class {name}:")
            members = [m for m in dir(obj) if not m.startswith("_") or m == "__init__"]
            body = []
            if obj.__text_signature__:
                inner = _signature(obj)[1:-1]
                body.append(f"    def __init__(self{', ' + inner if inner else ''}) -> None: ...")
            for member in members:
                if member == "__init__":
                    continue
                attr = getattr(obj, member)
                kind = type(attr).__name__
                if kind == "getset_descriptor":
                    body.append("    @property")
                    body.append(f"    def {member}(self) -> Any: ...")
                elif kind in ("method_descriptor", "builtin_function_or_method"):
                    sig = _signature(attr)
                    if kind == "builtin_function_or_method":  # static or class method
                        body.append("    @staticmethod")
                    body.append(f"    def {member}{sig} -> Any: ...")
                elif kind == "classmethod_descriptor":
                    body.append("    @classmethod")
                    body.append(f"    def {member}{_signature(attr)} -> Any: ...")
            out.extend(body or ["    ..."])
            out.append("")
        elif callable(obj):
            out.append(f"def {name}{_signature(obj)} -> Any: ...")
    return "\n".join(out) + "\n"


def main() -> int:
    import sylva._core as core

    target = Path(__file__).resolve().parents[1] / "python" / "sylva" / "_core.pyi"
    text = render(core)
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            print(f"{target} is out of date; run scripts/gen_core_stub.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text)
    print(f"wrote {target} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
